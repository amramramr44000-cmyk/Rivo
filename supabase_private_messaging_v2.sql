create or replace function public.rivo_cleanup_message_upload(p_bucket_id text, p_storage_path text)
returns boolean language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if p_bucket_id not in ('rivo-voice','rivo-message-media') then return false; end if;
  if p_storage_path is null or (storage.foldername(p_storage_path))[1] <> auth.uid()::text then return false; end if;
  if p_bucket_id='rivo-voice' and exists(select 1 from public.rivo_voice_messages where storage_path=p_storage_path) then return false; end if;
  if p_bucket_id='rivo-message-media' and exists(select 1 from public.rivo_message_attachments where storage_path=p_storage_path) then return false; end if;
  return true;
end; $$;
revoke all on function public.rivo_cleanup_message_upload(text,text) from public;
grant execute on function public.rivo_cleanup_message_upload(text,text) to authenticated;

create or replace function public.rivo_mark_messages_read(p_other_username text)
returns integer language plpgsql security definer set search_path = public as $$
declare me_id uuid := auth.uid(); other_id uuid; changed integer;
begin
  if me_id is null then raise exception 'Not signed in'; end if;
  select id into other_id from public.profiles where username=lower(trim(both '@' from p_other_username));
  if other_id is null or other_id=me_id then return 0; end if;
  update public.rivo_messages set read_at=now()
  where sender_id=other_id and receiver_id=me_id and read_at is null;
  get diagnostics changed = row_count;
  return changed;
end; $$;
revoke all on function public.rivo_mark_messages_read(text) from public;
grant execute on function public.rivo_mark_messages_read(text) to authenticated;

create or replace function public.rivo_edit_message(p_message_id bigint, p_content text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare me_id uuid := auth.uid(); value text := trim(coalesce(p_content,'')); msg public.rivo_messages;
begin
  if me_id is null then raise exception 'Not signed in'; end if;
  if char_length(value)<1 or char_length(value)>2000 then raise exception 'Message must be between 1 and 2000 characters'; end if;
  select * into msg from public.rivo_messages where id=p_message_id for update;
  if msg.id is null or msg.sender_id<>me_id then raise exception 'Message not found or not yours'; end if;
  if msg.content in ('[voice]','[image]') or exists(select 1 from public.rivo_voice_messages where message_id=msg.id)
     or exists(select 1 from public.rivo_message_attachments where message_id=msg.id) then
    raise exception 'Only text messages can be edited';
  end if;
  update public.rivo_messages set content=value, edited_at=now() where id=msg.id returning * into msg;
  return jsonb_build_object('id',msg.id,'content',msg.content,'edited_at',msg.edited_at);
end; $$;
revoke all on function public.rivo_edit_message(bigint,text) from public;
grant execute on function public.rivo_edit_message(bigint,text) to authenticated;

create or replace function public.rivo_message_action(p_message_id bigint, p_scope text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare me_id uuid := auth.uid(); msg public.rivo_messages; voice_path text; image_path text;
begin
  if me_id is null then raise exception 'Not signed in'; end if;
  if p_scope not in ('me','everyone') then raise exception 'Invalid delete scope'; end if;
  select * into msg from public.rivo_messages where id=p_message_id for update;
  if msg.id is null or (msg.sender_id<>me_id and msg.receiver_id<>me_id) then raise exception 'Message not found'; end if;
  if p_scope='everyone' then
    if msg.sender_id<>me_id then raise exception 'Only the sender can delete for everyone'; end if;
    select storage_path into voice_path from public.rivo_voice_messages where message_id=msg.id;
    select storage_path into image_path from public.rivo_message_attachments where message_id=msg.id;
    -- Return storage paths so the authenticated client can remove the binaries through
    -- Supabase Storage's API (direct SQL deletes from storage.objects do not reliably
    -- delete the underlying object-store bytes). The message metadata is removed atomically.
    delete from public.rivo_messages where id=msg.id;
    return jsonb_build_object('scope','everyone','message_id',p_message_id,
      'voice_path',voice_path,'image_path',image_path);
  end if;
  insert into public.rivo_message_hidden(message_id,user_id) values(msg.id,me_id) on conflict do nothing;
  return jsonb_build_object('scope','me','message_id',p_message_id);
end; $$;
revoke all on function public.rivo_message_action(bigint,text) from public;
grant execute on function public.rivo_message_action(bigint,text) to authenticated;

-- Unified message fetch, preserving reactions and existing private voice messages while
-- adding image metadata, read receipt, edit time, and per-user hide behavior.
create or replace function public.rivo_get_messages(p_other_username text, p_limit integer default 80)
returns setof jsonb language plpgsql security definer set search_path=public as $$
declare me_id uuid := auth.uid(); other_id uuid;
begin
  select id into other_id from public.profiles where username=lower(trim(both '@' from p_other_username));
  if me_id is null then raise exception 'Not signed in'; end if;
  if other_id is null then raise exception 'User not found'; end if;
  return query
  select jsonb_build_object(
    'id',m.id,'sender_username',s.username,'receiver_username',r.username,
    'content',case when v.message_id is not null or a.message_id is not null then '' else m.content end,
    'message_type',case when v.message_id is not null then 'voice' when a.message_id is not null then 'image' else 'text' end,
    'voice_path',v.storage_path,'voice_duration',v.duration_ms,
    'image_path',a.storage_path,'image_mime',a.mime_type,
    'created_at',m.created_at,'read_at',m.read_at,'edited_at',m.edited_at,
    'reactions',coalesce((select jsonb_agg(jsonb_build_object('reaction',x.reaction,'count',x.count,'me',x.me) order by x.reaction)
      from (select mr.reaction,count(*)::int as count,bool_or(mr.user_id=me_id) as me
        from public.rivo_message_reactions mr where mr.message_id=m.id group by mr.reaction) x),'[]'::jsonb)
  )
  from public.rivo_messages m
  join public.profiles s on s.id=m.sender_id
  join public.profiles r on r.id=m.receiver_id
  left join public.rivo_voice_messages v on v.message_id=m.id
  left join public.rivo_message_attachments a on a.message_id=m.id
  where ((m.sender_id=me_id and m.receiver_id=other_id) or (m.sender_id=other_id and m.receiver_id=me_id))
    and not exists(select 1 from public.rivo_message_hidden h where h.message_id=m.id and h.user_id=me_id)
  order by m.created_at desc
  limit greatest(1,least(coalesce(p_limit,80),200));
end; $$;
revoke all on function public.rivo_get_messages(text,integer) from public;
grant execute on function public.rivo_get_messages(text,integer) to authenticated;

-- Conversation preview respects per-user hidden messages and avoids exposing [voice]/[image] markers.
create or replace function public.rivo_list_conversations()
returns setof jsonb language sql security definer set search_path=public as $$
with ranked as (
  select m.*, row_number() over (
    partition by least(m.sender_id,m.receiver_id), greatest(m.sender_id,m.receiver_id)
    order by m.created_at desc, m.id desc
  ) as rn
  from public.rivo_messages m
  where (m.sender_id=auth.uid() or m.receiver_id=auth.uid())
    and not exists(select 1 from public.rivo_message_hidden h where h.message_id=m.id and h.user_id=auth.uid())
), latest as (select * from ranked where rn=1)
select jsonb_build_object(
  'userId',other.id,'username',other.username,
  'displayName',coalesce(other.public_data->>'displayName',other.username),
  'avatar',coalesce(other.public_data->>'avatar',''),
  'lastMessage',case when v.message_id is not null then 'Voice message' when a.message_id is not null then 'Photo' else latest.content end,
  'createdAt',latest.created_at,
  'updatedLabel',to_char(latest.created_at at time zone 'UTC','Mon DD')
)
from latest
join public.profiles other on other.id=case when latest.sender_id=auth.uid() then latest.receiver_id else latest.sender_id end
left join public.rivo_voice_messages v on v.message_id=latest.id
left join public.rivo_message_attachments a on a.message_id=latest.id
order by latest.created_at desc;
$$;
revoke all on function public.rivo_list_conversations() from public;
grant execute on function public.rivo_list_conversations() to authenticated;

