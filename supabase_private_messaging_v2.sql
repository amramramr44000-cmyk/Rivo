-- Rivo private messaging v2: reliable voice idempotency, private images,
-- read receipts, edit/delete scopes and hidden per-user messages.
-- Additive migration: does not delete/overwrite user data. Review and run once
-- in Supabase SQL Editor on staging first, then production after backup.

begin;

alter table public.rivo_messages
  add column if not exists read_at timestamptz,
  add column if not exists edited_at timestamptz;

-- Keep the existing voice table and rows. Add only the idempotency field.
create table if not exists public.rivo_voice_messages (
  id bigint generated by default as identity primary key,
  message_id bigint not null unique references public.rivo_messages(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null unique,
  duration_ms integer not null check (duration_ms between 1 and 300000),
  mime_type text not null default 'audio/webm',
  created_at timestamptz not null default now()
);
alter table public.rivo_voice_messages add column if not exists client_message_key uuid;
create unique index if not exists rivo_voice_client_key_uidx
  on public.rivo_voice_messages(sender_id, client_message_key)
  where client_message_key is not null;
create index if not exists rivo_voice_sender_receiver_idx
  on public.rivo_voice_messages(sender_id, receiver_id, created_at desc);
alter table public.rivo_voice_messages enable row level security;
-- Explicit grants are needed by Storage RLS predicates; table RLS still limits
-- row visibility to the two participants in each private conversation.
grant select on public.rivo_voice_messages to authenticated;
drop policy if exists rivo_voice_select_participants on public.rivo_voice_messages;
create policy rivo_voice_select_participants on public.rivo_voice_messages
  for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);

-- Message attachment metadata is private. Image bytes live in a separate private bucket,
-- not the public profile/post bucket.
create table if not exists public.rivo_message_attachments (
  message_id bigint primary key references public.rivo_messages(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null unique,
  mime_type text not null check (mime_type in ('image/webp','image/jpeg','image/png','image/gif','image/avif')),
  byte_size integer not null check (byte_size between 1 and 8388608),
  created_at timestamptz not null default now()
);
create index if not exists rivo_message_attachments_receiver_idx
  on public.rivo_message_attachments(receiver_id, created_at desc);
alter table public.rivo_message_attachments enable row level security;
grant select on public.rivo_message_attachments to authenticated;
drop policy if exists rivo_message_attachments_select_participants on public.rivo_message_attachments;
create policy rivo_message_attachments_select_participants on public.rivo_message_attachments
  for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);

create table if not exists public.rivo_message_hidden (
  message_id bigint not null references public.rivo_messages(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(message_id, user_id)
);
alter table public.rivo_message_hidden enable row level security;
drop policy if exists rivo_message_hidden_select_self on public.rivo_message_hidden;
create policy rivo_message_hidden_select_self on public.rivo_message_hidden
  for select to authenticated using (user_id = auth.uid());

insert into storage.buckets (id, name, public)
values ('rivo-voice','rivo-voice',false)
on conflict (id) do update set public = false, file_size_limit = 8388608,
  allowed_mime_types = array['audio/webm','audio/ogg','audio/mp4','audio/mpeg','audio/aac','audio/3gpp'];
update storage.buckets set file_size_limit = 8388608,
  allowed_mime_types = array['audio/webm','audio/ogg','audio/mp4','audio/mpeg','audio/aac','audio/3gpp']
where id = 'rivo-voice';
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('rivo-message-media','rivo-message-media',false,8388608, array['image/webp','image/jpeg','image/png','image/gif','image/avif'])
on conflict (id) do update set public = false, file_size_limit = 8388608,
  allowed_mime_types = array['image/webp','image/jpeg','image/png','image/gif','image/avif'];

drop policy if exists rivo_voice_storage_insert_owner on storage.objects;
create policy rivo_voice_storage_insert_owner on storage.objects for insert to authenticated
  with check (bucket_id='rivo-voice' and (storage.foldername(name))[1]=auth.uid()::text and name like auth.uid()::text || '/voice/%');
drop policy if exists rivo_voice_storage_select_participants on storage.objects;
create policy rivo_voice_storage_select_participants on storage.objects for select to authenticated
  using (bucket_id='rivo-voice' and exists(select 1 from public.rivo_voice_messages v where v.storage_path=name and (v.sender_id=auth.uid() or v.receiver_id=auth.uid())));
drop policy if exists rivo_voice_storage_delete_owner on storage.objects;
create policy rivo_voice_storage_delete_owner on storage.objects for delete to authenticated
  using (bucket_id='rivo-voice' and (storage.foldername(name))[1]=auth.uid()::text and name like auth.uid()::text || '/voice/%');

-- Private image upload: path must start with the authenticated user's UUID.
drop policy if exists rivo_message_media_insert_owner on storage.objects;
create policy rivo_message_media_insert_owner on storage.objects
  for insert to authenticated
  with check (bucket_id = 'rivo-message-media'
    and (storage.foldername(name))[1] = auth.uid()::text
    and name like auth.uid()::text || '/messages/%');
drop policy if exists rivo_message_media_select_participants on storage.objects;
create policy rivo_message_media_select_participants on storage.objects
  for select to authenticated
  using (bucket_id = 'rivo-message-media' and exists (
    select 1 from public.rivo_message_attachments a
    where a.storage_path = name and (a.sender_id = auth.uid() or a.receiver_id = auth.uid())
  ));
drop policy if exists rivo_message_media_delete_owner on storage.objects;
create policy rivo_message_media_delete_owner on storage.objects
  for delete to authenticated
  using (bucket_id = 'rivo-message-media'
    and (storage.foldername(name))[1] = auth.uid()::text
    and name like auth.uid()::text || '/messages/%');

-- This function is idempotent for the same client key. Retries return the original
-- message rather than creating a second voice bubble. The upload path is validated.
create or replace function public.rivo_send_voice_message_v2(
  p_receiver_username text,
  p_storage_path text,
  p_duration_ms integer,
  p_mime_type text,
  p_client_message_key uuid
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  me public.profiles;
  target public.profiles;
  msg public.rivo_messages;
  voice public.rivo_voice_messages;
  can_receive text;
  are_friends boolean := false;
  path text := trim(coalesce(p_storage_path,''));
  mt text := lower(split_part(coalesce(p_mime_type,'audio/webm'),';',1));
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if p_client_message_key is null then raise exception 'Missing client message key'; end if;
  perform pg_advisory_xact_lock(hashtext(auth.uid()::text), hashtext(p_client_message_key::text));

  select v, m into voice, msg
  from public.rivo_voice_messages v join public.rivo_messages m on m.id = v.message_id
  where v.sender_id = auth.uid() and v.client_message_key = p_client_message_key;
  if voice.message_id is not null then
    select * into target from public.profiles where id = voice.receiver_id;
    return jsonb_build_object('id',msg.id,'sender_username',(select username from public.profiles where id=msg.sender_id),
      'receiver_username',target.username,'content','','message_type','voice','voice_path',voice.storage_path,
      'voice_duration',voice.duration_ms,'created_at',msg.created_at,'read_at',msg.read_at,'edited_at',msg.edited_at);
  end if;

  if p_duration_ms is null or p_duration_ms < 1 or p_duration_ms > 300000 then raise exception 'Invalid voice duration'; end if;
  if mt not in ('audio/webm','audio/ogg','audio/mp4','audio/mpeg','audio/aac','audio/3gpp') then raise exception 'Unsupported voice audio format'; end if;
  if path = '' or path not like auth.uid()::text || '/voice/%' then raise exception 'Invalid voice storage path'; end if;
  if not exists(select 1 from storage.objects o where o.bucket_id='rivo-voice' and o.name=path) then raise exception 'Voice upload was not found'; end if;
  select * into me from public.profiles where id=auth.uid();
  select * into target from public.profiles where username=lower(trim(both '@' from p_receiver_username));
  if me.id is null or target.id is null then raise exception 'User not found'; end if;
  if me.id = target.id then raise exception 'You cannot message yourself'; end if;
  if me.is_banned then raise exception 'Your account is blocked'; end if;
  if target.is_banned then raise exception 'This account is unavailable'; end if;
  can_receive := coalesce(target.private_data->'messageSettings'->>'whoCanMessage','everyone');
  if can_receive='nobody' then raise exception 'This user has closed their messages'; end if;
  are_friends := coalesce(target.public_data->'friends','[]'::jsonb) ? me.username;
  if can_receive='friends' and not are_friends then raise exception 'This user accepts messages from friends only'; end if;

  insert into public.rivo_messages(sender_id,receiver_id,content) values(me.id,target.id,'[voice]') returning * into msg;
  insert into public.rivo_voice_messages(message_id,sender_id,receiver_id,storage_path,duration_ms,mime_type,client_message_key)
    values(msg.id,me.id,target.id,path,p_duration_ms,coalesce(nullif(p_mime_type,''),'audio/webm'),p_client_message_key)
    returning * into voice;
  perform public.rivo_write_notification(target.id,me.id,'message',me.username||' sent you a voice message',jsonb_build_object('message_id',msg.id,'username',me.username,'voice',true));
  return jsonb_build_object('id',msg.id,'sender_username',me.username,'receiver_username',target.username,
    'content','','message_type','voice','voice_path',voice.storage_path,'voice_duration',voice.duration_ms,
    'created_at',msg.created_at,'read_at',msg.read_at,'edited_at',msg.edited_at,'reactions','[]'::jsonb);
exception when unique_violation then
  select v.* into voice from public.rivo_voice_messages v
  where v.sender_id=auth.uid() and v.client_message_key=p_client_message_key;
  if voice.message_id is null then raise; end if;
  select * into msg from public.rivo_messages where id=voice.message_id;
  select * into target from public.profiles where id=voice.receiver_id;
  return jsonb_build_object('id',msg.id,'sender_username',(select username from public.profiles where id=msg.sender_id),
    'receiver_username',target.username,'content','','message_type','voice','voice_path',voice.storage_path,
    'voice_duration',voice.duration_ms,'created_at',msg.created_at,'read_at',msg.read_at,'edited_at',msg.edited_at);
end; $$;
revoke all on function public.rivo_send_voice_message_v2(text,text,integer,text,uuid) from public;
grant execute on function public.rivo_send_voice_message_v2(text,text,integer,text,uuid) to authenticated;

