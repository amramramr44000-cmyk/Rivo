end $$;

-- Admin update RPC used by the Edge Function to safely update the public profile fields.
create or replace function public.rivo_admin_update_profile(p_current_username text,p_new_username text,p_display_name text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare target public.profiles; oldu text:=lower(trim(both '@' from p_current_username)); newu text:=lower(trim(both '@' from p_new_username));
begin
  if not public.rivo_is_admin(auth.uid()) then raise exception 'Access denied'; end if;
  select * into target from public.profiles where username=oldu for update;
  if target.id is null then raise exception 'User not found'; end if;
  if newu is null or newu !~ '^[a-z0-9][a-z0-9._-]{1,24}[a-z0-9]$' then raise exception 'Invalid username'; end if;
  if newu <> oldu and exists(select 1 from public.profiles where username=newu) then raise exception 'Username already exists'; end if;
  update public.profiles set username=newu, public_data=jsonb_set(coalesce(public_data,'{}'::jsonb),'{displayName}',to_jsonb(coalesce(nullif(trim(p_display_name),''),newu)),true), updated_at=now() where id=target.id;
  return jsonb_build_object('user_id',target.id,'username',newu,'display_name',coalesce(nullif(trim(p_display_name),''),newu));
end; $$;
revoke all on function public.rivo_admin_update_profile(text,text,text) from public;
grant execute on function public.rivo_admin_update_profile(text,text,text) to authenticated;
